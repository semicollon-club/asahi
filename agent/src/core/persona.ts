// 턴별 컨텍스트(역할·DM여부·워커 연결)로 시스템 프롬프트를 만든다. 능력 계층(§7.1)을 반영한다.
export function buildSystemPrompt(ctx: PersonaContext): string {
  return [
    IDENTITY,
    QUALITY,
    MEMORY,
    buildCapabilityBlock(ctx),
  ].filter((block) => block.length > 0).join("\n\n");
}
