// 워커의 이상을 소유자에게 알린다 — 지금 보는 것은 "붙어 있던 워커가 사라졌는가" 하나다.
//
// 2026-09-03 까지는 "워커가 봇보다 낡았는가"를 보는 decideStaleAlerts 가 여기 함께 있었다.
// 봇 커밋(RAILWAY_GIT_COMMIT_SHA)과 워커 커밋을 SHA 로 견주어, 15분 넘게 어긋나면 자동 갱신이
// 막혔다고 알리는 판정이었다. 그것을 지운 이유는 임계값이 아니라 비교 자체가 성립하지 않게
// 됐기 때문이다 — 봇은 배포 브랜치(production)의 머지 커밋을, 워커는 자기 클론의 main HEAD 를
// 보고하는데, 2026-09-02 부터 그 둘은 서로 다른 갈래라 같아질 수 있는 경우가 아예 없다. 게다가
// asahi 는 watch path(/agent/**)로 배포돼 봇 커밋이 브랜치 팁을 따라가지도 않는다(두 원인의
// 자세한 사정은 core/tools.ts 의 runtimeInfoHandler 머리말).
//
// 그 결과 알림은 "갱신이 막힌 날"이 아니라 "봇이 배포될 때마다" 한 번씩, 워커가 멀쩡히 최신인
// 상태로 나갔다. 늑대소년이 된 알림은 없는 알림보다 나쁘다 — 같은 타이머에서 같은 DM 으로 나가는
// 아래 부재 알림까지 함께 무시하게 만들고, 그 부재 알림이야말로 2026-08-01 의 13시간 반 사고를
// 잡으라고 만든 것이다. 낡음을 다시 판정하려면 커밋 신원이 아니라 실제로 돌고 있는 코드를 견주는
// 장치가 필요하고, 그것은 별도 작업이다.

// 워커가 아예 사라진 것을 알린다. 낡음 판정이 있던 시절에는 그 짝이었고 보는 것이 정반대였다 —
// 저쪽은 "붙어 있는 워커의 커밋이 낡았나", 이쪽은 "붙어 있던 워커가 없어졌나". 저쪽이 사라진
// 지금은 이것이 워커 이상을 알리는 유일한 경로다.
//
// 이 함수가 생긴 이유(2026-08-01): 워커가 13시간 반 사라져 있었는데 아무 알림도 오지 않았다.
// 그때 유일하던 낡음 판정은 workersInfo() 가 돌려주는 "붙어 있는" 워커만 훑었으므로, 워커가
// 통째로 없어지면 훑을 대상 자체가 없어 조용했다. 사라진 것이야말로 가장 먼저 알아야 할
// 상태인데 유일하게 안 알리던 상태였다.
//
// 값은 "마지막으로 붙어 있는 것을 본 시각"이고, -1 은 "이미 알렸다"는 표식이다.
export type SeenState = Map<string, number>;

// 이 봇 프로세스가 사는 동안 "붙은 적 있는" 워커만 대상으로 삼는다. 등록은 돼 있지만 며칠째
// 안 붙는 워커(owner-laptop 같은)까지 알리면 매번 울려 아무도 안 보게 된다 — 그렇게 되면 정작
// 공유 워커가 죽은 날에도 그 줄이 묻힌다. 봇이 재배포되면 이 맵도 비워지는데, 그때는 아직
// 아무것도 "붙은 적 없는" 상태라 첫 연결부터 다시 세면 되므로 무해하다.
export function decideMissingAlerts(o: {
  connected: string[];
  now: number;
  seen: SeenState;
  thresholdMs: number;
}): string[] {
  const live = new Set(o.connected);
  for (const id of live) o.seen.set(id, o.now); // 복귀가 셈을 되돌린다 — 두 번째 사고를 놓치지 않으려고
  const alerts: string[] = [];
  for (const [id, since] of o.seen) {
    if (live.has(id) || since === -1) continue;
    if (o.now - since >= o.thresholdMs) {
      o.seen.set(id, -1);
      alerts.push(
        `워커 ${id} 가 ${Math.round((o.now - since) / 60_000)}분째 붙어 있지 않아요. ` +
          `미니PC 가 꺼져 있거나, 갱신 뒤 워커가 다시 뜨지 못했을 수 있어요 — ` +
          `미니PC 의 갱신 로그(C:\\asahi-worker\\update-worker.log)부터 확인해 주세요.`,
      );
    }
  }
  return alerts;
}
